module.exports = async (page) => {
  const checks = [];
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  const check = (name, passed) => {
    if (!passed) throw new Error(name);
    checks.push(name);
  };
  const text = selector => page.locator(selector).textContent();
  const stage = number => page.locator(`[data-stage="${number}"]`).click();
  const nextJob = () => page.locator("#job-next").click();
  const nextDemo = () => page.locator("#next").click();
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.reload();
  await page.setViewportSize({ width: 1440, height: 1100 });
  check("Five selectable designs and comparison rows", await page.locator("[data-stage]").count() === 5 && await page.locator("[data-stage-row]").count() === 5);
  check("Guide opens with regional storage and separate processing concepts", (await text("#boundaries-title")).includes("service boundaries") && (await page.locator(".fundamentals").first().textContent()).includes("up to 24 hours"));
  check("Baseline is direct CU without a gateway", await page.locator('[data-node="cu"]').count() === 1 && await page.locator('[data-node="gateway"]').count() === 0);
  check("Previous stage is bounded at stage one", await page.locator("#stage-previous").isDisabled());
  await nextJob();
  check("Baseline request highlights client to CU", await page.locator('[data-edge="submit"]').getAttribute("class").then(value => value.includes("highlight")));
  await stage(1);
  check("Model step keeps the CU and OCR endpoints", await page.locator('[data-node="cu"]').count() === 1 && await page.locator('[data-node="ocr"]').count() === 1 && await page.locator('[data-node^="model-capacity-"]').count() === 2);
  check("Model step does not broaden OCR", await page.locator('[data-node^="ocr-capacity-"]').count() === 0 && (await text("#stage-limit")).includes("OCR processing scope is unchanged"));
  check("Model step names the actual deployment SKUs", (await text("#stage-setting")).includes("DataZoneStandard") && (await text("#stage-setting")).includes("GlobalStandard"));
  await nextJob(); await nextJob();
  check("Unchanged OCR flow highlights both directions", await page.locator('[data-edge="parse"].highlight').count() === 1 && await page.locator('[data-edge="parsed"].highlight').count() === 1);
  await nextJob();
  check("Model step highlights model inference capacity", await page.locator('[data-edge="infer"].highlight').count() === 1 && await page.locator('[data-edge="model-route-a"].highlight').count() === 1 && (await text("#maturity-job-status")).includes("OCR-only requests skip"));
  await page.locator("#model-route").click();
  check("Model step can illustrate alternate eligible capacity", await page.locator('[data-edge="model-route-b"].highlight').count() === 1);
  await stage(2);
  check("OCR step adds capacity without removing model capacity", await page.locator('[data-node^="ocr-capacity-"]').count() === 2 && await page.locator('[data-node^="model-capacity-"]').count() === 2);
  check("OCR setting names all processingLocation values", (await text("#stage-setting")).includes("OCR processingLocation: geography, dataZone or global"));
  check("OCR support is scoped to the documented analyzers", (await text("#stage-limit")).includes("prebuilt-read and prebuilt-layout"));
  await page.locator("#ocr-route").click();
  check("OCR alternate capacity is independent of model routing", await page.locator('[data-edge="ocr-route-b"].highlight').count() === 1 && await page.locator("#model-route").getAttribute("aria-pressed") === "false");
  await page.locator("#model-route").click();
  check("Model alternate capacity preserves OCR selection", await page.locator('[data-edge="model-route-b"].highlight').count() === 1 && await page.locator("#ocr-route").getAttribute("aria-pressed") === "true");
  await nextJob();
  check("Result returns to the same regional job owner", (await text("#maturity-job-status")).includes("up-to-24-hour retention"));
  await stage(3);
  check("Step four has one gateway and two CU resources", await page.locator('[data-node="gateway"]').count() === 1 && await page.locator('[data-node^="cu-"]').count() === 2);
  check("Step-four link targets the separate walkthrough", await page.locator("#stage-demo-link").getAttribute("href") === "single-apim-failover.html");
  await page.locator("#stage-demo-link").click();
  await page.waitForURL(/single-apim-failover\.html$/);
  check("Step-four link opens the walkthrough", await page.locator("#demo-title").isVisible() && await page.locator('a[href="README.html"]').count() >= 1);
  await page.goBack();
  await page.waitForURL(/README\.html$|\/$/);
  check("README keeps a prominent link to the demo page", await page.locator('a[href="single-apim-failover.html"]').count() >= 2 && await page.locator("#demo").count() === 0);
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.locator('[data-stage="4"]').click();
  check("Step five has two APIMs and DNS", await page.locator('[data-node^="gateway-"]').count() === 2 && await page.locator('[data-node="dns"]').count() === 1);
  check("Step five is explicitly not implemented and trust-aware", (await text("#stage-scope")).includes("not implemented") && (await text("#stage-caveat")).includes("subscription identity"));
  check("Next design is bounded at step five", await page.locator("#stage-next").isDisabled());
  await page.locator("#region-outage").click();
  await nextJob();
  check("Outage sends fresh DNS selection to B after cache expiry", await page.locator('[data-edge="dns-b"].highlight').count() === 1 && (await text("#maturity-job-status")).includes("DNS cache expiry"));
  await nextJob();
  check("HTTPS goes directly to B, not through DNS", await page.locator('[data-edge="submit-b"].highlight').count() === 1 && await page.locator('[data-edge="dns-query"].highlight').count() === 0);
  check("Primary region is visibly marked unavailable", await page.locator('[data-node="gateway-a"] .unavailable').count() === 1);
  await nextJob(); await nextJob();
  check("Accepted response flows back toward the client", await page.locator('[data-edge="accepted-b"].highlight').count() === 1 && await page.locator('[data-edge="return-b"].highlight').count() === 1);
  await page.locator("#region-outage").click();
  check("Outage reset clears old job steps", (await text("#maturity-job-status")).startsWith("Ready."));
  await stage(0);
  await page.locator("#job-play").click();
  await page.waitForTimeout(2400);
  check("Synthetic playback advances", (await text("#maturity-job-status")).startsWith("2."));
  await page.locator("#job-play").click();
  const pausedStep = await text("#maturity-job-status");
  await page.waitForTimeout(2400);
  check("Synthetic playback pause is stable", await text("#maturity-job-status") === pausedStep);
  await page.locator("#job-next").click();
  await page.locator("#job-next").click();
  check("Synthetic job ends without looping", await page.locator("#job-next").isDisabled());
  await page.locator("#job-play").click();
  check("Completed synthetic job can restart", (await text("#maturity-job-status")).startsWith("1."));
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.waitForFunction(() => !document.getElementById("maturity-motion").checked);
  check("Reduced motion stops diagram animation", await page.evaluate(() => !document.getElementById("maturity-motion").checked && !document.getElementById("maturity-diagram").classList.contains("maturity-playing")));
  await page.locator('[data-stage="1"]').focus();
  await page.keyboard.press("Enter");
  check("Stage keyboard activation works", await page.locator('[data-stage="1"]').getAttribute("aria-pressed") === "true");
  await page.keyboard.press("Tab");
  await page.keyboard.press("Space");
  check("Stage Tab and Space navigation works", await page.locator('[data-stage="2"]').getAttribute("aria-pressed") === "true");
  check("README has one H1 and no console errors yet", await page.locator("h1").count() === 1 && errors.length === 0);
  await page.goto(new URL("single-apim-failover.html", page.url()).href);
  await page.emulateMedia({ reducedMotion: "reduce" });
  check("Demo page reduced motion disables path animation", await page.evaluate(() => !document.getElementById("motion").checked));
  await page.locator('[data-scenario="normal"]').click();
  await nextDemo();
  check("Acceptance rewrites CU Operation-Location to signed APIM URL", (await text("#before")).includes("cu-primary.example.invalid") && (await text("#after")).includes("gateway-token="));
  await nextDemo();
  check("Polling strips token on backend hop", (await text("#before")).includes("gateway-token=") && !(await text("#after")).includes("gateway-token="));
  await page.locator('[data-scenario="degraded"]').click();
  await nextDemo(); await nextDemo();
  check("Exactly sixty seconds does not switch", (await text("#step-note")).includes("exactly 60s does not switch"));
  await nextDemo();
  check("Slow successful result qualifies as completion-latency", (await text("#step-note")).includes("completion-latency") && (await text("#after")).includes('"status":"Succeeded"'));
  check("Overdue pending results remain a documented trigger", (await page.locator("#trigger-title").locator("xpath=..").textContent()).includes("pending-latency"));
  check("Succeeded over threshold is documented as completion-latency", (await page.locator("#trigger-title").locator("xpath=..").textContent()).includes("completion-latency"));
  check("No health endpoint is depicted", !(await page.content()).includes("/health/cu"));
  await nextDemo();
  check("ARM acceptance is not runtime activation", (await text("#management-state")).includes("secondary") && (await text("#active-backend")).includes("primary"));
  await page.locator('[data-scenario="failover"]').click();
  await nextDemo(); await nextDemo(); await nextDemo();
  check("Old primary operation stays pinned after failover", (await text("#active-backend")).includes("secondary") && (await text("#after")).includes("cu-primary.example.invalid"));
  await nextDemo();
  check("Threshold restoration leaves selection sticky", (await text("#before")).includes("secondary-cu (unchanged)"));
  for (const width of [1440, 768, 375]) {
    await page.setViewportSize({ width, height: 1000 });
    check(`No page-wide overflow at ${width}px`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  };
  await page.locator("details").evaluateAll(elements => elements.forEach(element => element.open = true));
  check("Expanded examples fit mobile", await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  check("No network-dependent page resources", await page.evaluate(() => performance.getEntriesByType("resource").length === 0 && document.querySelector('meta[http-equiv="Content-Security-Policy"]').content.includes("connect-src 'none'")));
  check("One H1 and valid deep-dive container", await page.locator("h1").count() === 1 && await page.locator("#demo #limits-title").count() === 1);
  check("No browser JavaScript errors", errors.length === 0);
  return { passed: checks.length, checks };
}
